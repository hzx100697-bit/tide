// 生产环境中应替换 / 叠加更严谨的分类模型，这里作为作品集演示的可解释规则版本

const CRISIS_PATTERNS = [
  /自杀/, /轻生/, /不想活/, /结束生命/, /了结自己/,
  /自残/, /伤害自己/, /割腕/,
  /活不下去/, /没有意义了/, /想消失/
];

export function detectCrisis(text) {
  if (!text) return false;
  return CRISIS_PATTERNS.some((pattern) => pattern.test(text));
}

